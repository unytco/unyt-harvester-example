// Writes src/agreement/template.generated.ts from the files in
// src/agreement/template/, so the packaged binary carries the code template
// without reading the filesystem. Runs before every build and test.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/agreement");
const read = (name) => readFileSync(join(dir, "template", name), "utf8");
const json = (name) => JSON.stringify(JSON.parse(read(name)), null, 2);

const out = `// Generated by scripts/embed-template.mjs from src/agreement/template/. Do not edit.
export const executionCodeRhai: string = ${JSON.stringify(read("execution_code.rhai"))};
export const agreementDefinitionInput = ${json("agreement_definition_input.json")} as const;
export const runtimeInputSignature = ${json("runtime_input_signature.json")} as const;
export const outputSignature = ${json("output_signature.json")} as const;
`;
writeFileSync(join(dir, "template.generated.ts"), out);
